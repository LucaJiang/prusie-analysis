"""Supplementary figure: layout of the offline HTML report.

Writes figures/supp_report.{pdf,svg,png}. Panel a is a schematic of the report
sections; panels b and c are screenshots of the report generated by
examples/post_analysis.py (prusie 948fd91) for the susieR FinemappingConvergence
toy example, rendered in headless Chromium at 900 px width and 2x scale. The
crops are stored in data/report_snippets/.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
os.environ.setdefault("MPLCONFIGDIR", str(PAPER / ".cache/matplotlib"))
sys.path.insert(0, str(PAPER / "scripts"))

from matplotlib import pyplot as plt
from matplotlib.patches import ConnectionPatch, FancyBboxPatch
from PIL import Image

from _bench_style import DOUBLE_COLUMN_IN, INK, INK2, MM, PRUSIE, panel_letter, save, style

SNIPPETS = PAPER / "03_results/report_snippets"
FIGURES = PAPER / "04_figures_tables/figures"

SECTIONS = (
    ("What to check first",
     "Flags for unconverged IBSS or sensitivity fits,\n"
     "ELBO decreases, refinement that changed credible\n"
     "sets or has a competing solution, credible sets\n"
     "lost under sensitivity settings, flagged LD"),
    ("Main results and resolution",
     "Credible sets with size, posterior mass, LD purity\n"
     "and effective number of variants; top candidates"),
    ("Analysis status",
     "Convergence assessment and IBSS stopping; refinement\n"
     "search with credible sets before and after; sensitivity\n"
     "fit status and credible-set recovery; LD compatibility"),
    ("Figures",
     "Locus overview, convergence and refinement traces,\n"
     "signal resolution, sensitivity, LD diagnostics"),
    ("Sensitivity and LD diagnostics",
     "Cross-setting signal relations and the LD flag rule"),
    ("Complete records and provenance",
     "Checks run, full stopping and refinement records,\n"
     "all components, CS audit and between-CS LD"),
    ("Machine-readable exports",
     "JSON summaries, TSV tables, saved fits, PNG/SVG figures"),
)
LINKS = {0: "b", 1: "b", 3: "c"}


def schematic(ax):
    ax.set_axis_off()
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    heights = [0.046 + 0.0215 * (body.count("\n") + 1) for _, body in SECTIONS]
    gap = 0.025
    pad = (0.995 - sum(heights) - gap * (len(SECTIONS) - 1)) / len(SECTIONS)
    heights = [h + pad for h in heights]
    anchors = {}
    y = 0.995
    for i, ((title, body), h) in enumerate(zip(SECTIONS, heights, strict=True)):
        linked = i in LINKS
        ax.add_patch(FancyBboxPatch(
            (0.01, y - h), 0.98, h, boxstyle="round,pad=0,rounding_size=0.015",
            facecolor="#eef4f9" if linked else "#f5f5f3",
            edgecolor=PRUSIE if linked else "#c9c8c3", lw=0.8 if linked else 0.6,
        ))
        ax.text(0.05, y - 0.012, f"{i + 1}  {title}", fontsize=7, fontweight="bold",
                color=INK, va="top")
        ax.text(0.05, y - 0.04, body, fontsize=6, color=INK2, va="top", linespacing=1.3)
        if linked:
            anchors[i] = (0.99, y - h / 2)
            ax.text(0.955, y - 0.012, LINKS[i], fontsize=7, fontweight="bold", color=PRUSIE,
                    va="top", ha="right")
        y -= h + gap
    return anchors


def snippet(ax, name):
    ax.imshow(Image.open(SNIPPETS / name), interpolation="lanczos")
    ax.set_xticks([])
    ax.set_yticks([])
    for spine in ax.spines.values():
        spine.set_visible(True)
        spine.set_edgecolor("#c9c8c3")
        spine.set_linewidth(0.6)


def main():
    style("prusie-report")
    fig = plt.figure(figsize=(DOUBLE_COLUMN_IN, 178 * MM))
    ax_a = fig.add_axes((0.005, 0.01, 0.43, 0.96))
    ax_b = fig.add_axes((0.47, 0.565, 0.525, 0.405))
    ax_c = fig.add_axes((0.47, 0.01, 0.525, 0.5))
    anchors = schematic(ax_a)
    snippet(ax_b, "checks_and_results.png")
    snippet(ax_c, "locus_overview.png")
    for i, target in ((0, ax_b), (3, ax_c)):
        fig.add_artist(ConnectionPatch(
            anchors[i], (0, 0.5), coordsA=ax_a.transData, coordsB=target.transAxes,
            color=PRUSIE, lw=0.7, arrowstyle="-|>", mutation_scale=7,
        ))
    panel_letter(ax_a, "a", x=0.0, y=1.005)
    panel_letter(ax_b, "b", x=-0.035, y=1.005)
    panel_letter(ax_c, "c", x=-0.035, y=1.005)
    save(fig, FIGURES, "supp_report")


if __name__ == "__main__":
    main()
